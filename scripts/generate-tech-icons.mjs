// Extracts only the brand icons the site uses from `simple-icons` into a small
// static module, so the full icon set never reaches the client bundle.
// Run with: npm run icons
import { writeFileSync } from "node:fs";
import * as si from "simple-icons";

const ICONS = {
  python: "siPython",
  django: "siDjango",
  fastapi: "siFastapi",
  flask: "siFlask",
  react: "siReact",
  typescript: "siTypescript",
  javascript: "siJavascript",
  html5: "siHtml5",
  css: "siCss",
  postgresql: "siPostgresql",
  mysql: "siMysql",
  mongodb: "siMongodb",
  redis: "siRedis",
  sqlite: "siSqlite",
  docker: "siDocker",
  kubernetes: "siKubernetes",
  langchain: "siLangchain",
  gemini: "siGooglegemini",
  huggingface: "siHuggingface",
  stripe: "siStripe",
  celery: "siCelery",
  graphql: "siGraphql",
  jwt: "siJsonwebtokens",
  pydantic: "siPydantic",
  git: "siGit",
  github: "siGithub",
  postman: "siPostman",
  jira: "siJira",
};

const entries = Object.entries(ICONS).map(([key, exportName]) => {
  const icon = si[exportName];
  if (!icon) throw new Error(`simple-icons has no export ${exportName}`);
  return `  ${key}: { title: ${JSON.stringify(icon.title)}, path: ${JSON.stringify(icon.path)} },`;
});

const out = `// Generated by scripts/generate-tech-icons.mjs from simple-icons (CC0). Do not edit by hand.
// Brand names and logos are trademarks of their respective owners.
export const techIcons = {
${entries.join("\n")}
} as const;

export type TechIconKey = keyof typeof techIcons;
`;

writeFileSync(new URL("../src/content/tech-icons.ts", import.meta.url), out);
console.log(`Wrote ${entries.length} icons to src/content/tech-icons.ts`);
